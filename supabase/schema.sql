-- Un joueur est "en jeu" s'il n'a pas quitte volontairement ET si son
-- navigateur a donne signe de vie recemment. 40 s de tolerance : bien plus
-- que l'intervalle de battement (15 s), donc un simple lag ne fait sauter
-- le tour de personne.
create or replace function public._tf_live_window()
returns interval language sql immutable as $$ select interval '40 seconds' $$;

create or replace function public._tf_touch(p_uid uuid, p_game_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  -- On n'ecrit QUE si l'etat change vraiment.
  --
  -- tf_players est publiee sur Realtime (replica identity full). Comme
  -- tf_state est appele toutes les 5 s par chaque telephone et qu'il passe
  -- ici, une ecriture inconditionnelle diffusait le battement de CHAQUE
  -- joueur a TOUS les autres : a N joueurs, N²/5 messages par seconde, et
  -- autant de rechargements de la liste — uniquement pour un horodatage que
  -- personne n'affiche. A partir de six telephones le canal saturait, tombait
  -- en boucle ("Reconnexion…"), les requetes se faisaient jeter par la limite
  -- de debit, et faute de battement qui passe les joueurs finissaient par
  -- s'afficher hors ligne alors qu'ils etaient bien la.
  --
  -- 10 s de pas, pour 40 s de fenetre de tolerance : trois battements de
  -- marge avant qu'un joueur soit considere parti. Un joueur marque hors
  -- ligne, lui, est reveille immediatement.
  update public.tf_players
     set last_seen = now(), connected = true
   where id = p_uid and game_id = p_game_id             -- WHERE obligatoire
     and (not connected or last_seen < now() - interval '10 seconds');
end;
$$;

-- Change de phase : incremente phase_seq, arme le chrono serveur, et
-- journalise l'evenement qui declenchera l'animation sur le plateau.
-- p_ms force la duree (chrono d'equipe repris la ou il s'etait arrete).
create or replace function public._tf_phase(
  p_game_id uuid,
  p_phase   text,
  p_type    text,
  p_payload jsonb default '{}'::jsonb,
  p_ms      integer default null
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_secs integer;
  v_seq  integer;
  v_ends timestamptz;
begin
  v_secs := public.tf_phase_seconds(p_phase);

  if p_ms is not null then
    v_ends := now() + (p_ms || ' milliseconds')::interval;
  elsif v_secs is not null then
    v_ends := now() + (v_secs || ' seconds')::interval;
  else
    v_ends := null;
  end if;

  update public.tf_games
     set phase            = p_phase,
         phase_seq        = phase_seq + 1,
         phase_started_at = now(),
         phase_ends_at    = v_ends,
         last_event       = coalesce(p_payload, '{}'::jsonb)
                              || jsonb_build_object('type', p_type),
         last_event_at    = now()
   where id = p_game_id                                  -- WHERE obligatoire
  returning phase_seq into v_seq;

  insert into public.tf_events (game_id, seq, type, payload)
       values (p_game_id, v_seq, p_type, coalesce(p_payload, '{}'::jsonb));
end;
$$;

-- Evenement pur, sans changement de phase (utile pour un beat d'animation).
create or replace function public._tf_event(p_game_id uuid, p_type text, p_payload jsonb)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare v_seq integer;
begin
  select phase_seq into v_seq from public.tf_games where id = p_game_id;
  insert into public.tf_events (game_id, seq, type, payload)
       values (p_game_id, v_seq, p_type, coalesce(p_payload, '{}'::jsonb));
end;
$$;

-- Tire une question jamais posee dans cette partie.
create or replace function public._tf_pick_question(p_game_id uuid)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_used integer[];
  v_id   integer;
begin
  select used_question_ids into v_used from public.tf_games where id = p_game_id;

  select q.id into v_id
    from public.tf_questions q
   where not (q.id = any (coalesce(v_used, '{}')))
     and exists (select 1 from public.tf_answers a where a.question_id = q.id)
   order by random()
   limit 1;

  -- Plus de 200 questions : impossible en 5 manches, mais on ne bloque
  -- jamais une partie pour autant.
  if v_id is null then
    select q.id into v_id from public.tf_questions q
     where exists (select 1 from public.tf_answers a where a.question_id = q.id)
     order by random() limit 1;
  end if;

  update public.tf_games
     set question_id = v_id,
         used_question_ids = array_append(coalesce(used_question_ids, '{}'), v_id)
   where id = p_game_id;                                 -- WHERE obligatoire

  return v_id;
end;
$$;

-- Designe les deux joueurs du face-a-face : celui qui en a fait le moins
-- dans chaque equipe. C'est ce qui fait tourner tout le monde.
create or replace function public._tf_pick_faceoff(p_game_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare v_r uuid; v_b uuid;
begin
  select id into v_r from public.tf_players
   where game_id = p_game_id and team = 'R'
     and connected and last_seen > now() - public._tf_live_window()
   order by faceoff_count, joined_at, id limit 1;
  if v_r is null then
    select id into v_r from public.tf_players
     where game_id = p_game_id and team = 'R'
     order by faceoff_count, joined_at, id limit 1;
  end if;

  select id into v_b from public.tf_players
   where game_id = p_game_id and team = 'B'
     and connected and last_seen > now() - public._tf_live_window()
   order by faceoff_count, joined_at, id limit 1;
  if v_b is null then
    select id into v_b from public.tf_players
     where game_id = p_game_id and team = 'B'
     order by faceoff_count, joined_at, id limit 1;
  end if;

  update public.tf_games
     set faceoff_r = v_r, faceoff_b = v_b,
         faceoff_tried = '{}', buzz_winner = null, buzz_at = null
   where id = p_game_id;                                 -- WHERE obligatoire

  update public.tf_players
     set faceoff_count = faceoff_count + 1
   where id in (v_r, v_b) and id is not null;            -- WHERE obligatoire
end;
$$;

-- Devoile une reponse et credite les points de la manche (x multiplicateur).
create or replace function public._tf_reveal(
  p_game_id   uuid,
  p_answer_id bigint,
  p_team      text,
  p_player_id uuid
)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_game    public.tf_games;
  v_answer  public.tf_answers;
  v_awarded integer;
  v_rows    integer;
begin
  select * into v_game from public.tf_games where id = p_game_id;
  select * into v_answer from public.tf_answers where id = p_answer_id;
  if v_answer.id is null then return 0; end if;

  v_awarded := v_answer.points * greatest(1, v_game.round_multiplier);

  insert into public.tf_reveals
        (game_id, round_number, answer_id, question_id, team, player_id, awarded)
       values (p_game_id, v_game.round_number, p_answer_id,
               v_answer.question_id, p_team, p_player_id, v_awarded)
  on conflict (game_id, round_number, answer_id) do nothing;

  get diagnostics v_rows = row_count;
  if v_rows = 0 then
    return 0;                       -- deja devoilee : on ne credite pas deux fois
  end if;

  update public.tf_games
     set round_points = round_points + v_awarded
   where id = p_game_id;                                 -- WHERE obligatoire

  return v_awarded;
end;
$$;

-- Nombre de reponses encore cachees pour la manche en cours.
create or replace function public._tf_hidden_left(p_game_id uuid)
returns integer
language sql
security definer
set search_path = public
as $$
  select count(*)::integer
    from public.tf_answers a
    join public.tf_games g on g.id = p_game_id
   where a.question_id = g.question_id
     and not exists (select 1 from public.tf_reveals r
                      where r.game_id = g.id
                        and r.round_number = g.round_number
                        and r.answer_id = a.id)
$$;

-- ---------------------------------------------------------------------
-- 5. MACHINE D'ETAT
--
--   LOBBY -> INTRO -> FACE_OFF -> BUZZING -> ANSWERING
--         -> CORRECT_ANSWER -> CONTROL_GRANTED -> TEAM_TURN
--         -> (CORRECT_ANSWER | WRONG_ANSWER)* -> THREE_STRIKES
--         -> STEAL -> STEAL_RESULT -> ROUND_RESULT -> ROUND_TRANSITION
--         -> (manche suivante | FINALE_INTRO)
--         -> FINALE_PLAYER_ONE -> FINALE_PLAYER_TWO -> FINALE_REVEAL
--         -> VICTORY
-- ---------------------------------------------------------------------

-- Ouvre une manche : nouvelle question, compteurs remis a zero, duel designe.
create or replace function public._tf_begin_round(p_game_id uuid, p_round integer)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_qid  integer;
  v_game public.tf_games;
begin
  update public.tf_games
     set round_number     = p_round,
         round_multiplier = public.tf_multiplier(p_round),
         round_points     = 0,
         strikes          = 0,
         control_team     = null,
         turn_order       = '{}',
         turn_index       = 0,
         active_player_id = null,
         team_ms_left     = public.tf_phase_seconds('TEAM_TURN') * 1000,
         steal_team       = null,
         steal_by         = null,
         steal_answer_id  = null,
         steal_raw        = null,
         steal_success    = null
   where id = p_game_id;                                 -- WHERE obligatoire

  v_qid := public._tf_pick_question(p_game_id);
  perform public._tf_pick_faceoff(p_game_id);

  select * into v_game from public.tf_games where id = p_game_id;

  perform public._tf_phase(p_game_id, 'FACE_OFF', 'face_off',
    jsonb_build_object(
      'round', p_round,
      'multiplier', public.tf_multiplier(p_round),
      'playerR', v_game.faceoff_r,
      'playerB', v_game.faceoff_b));
end;
$$;

-- Construit la rotation de l'equipe qui prend le controle, en commencant
-- par le joueur qui a gagne le face-a-face.
create or replace function public._tf_begin_team_turn(p_game_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_game   public.tf_games;
  v_ids    uuid[];
  v_order  uuid[] := '{}';
  v_start  integer := 1;
  i        integer;
  n        integer;
begin
  select * into v_game from public.tf_games where id = p_game_id;

  select array_agg(id order by joined_at, id) into v_ids
    from public.tf_players
   where game_id = p_game_id and team = v_game.control_team;

  n := coalesce(array_length(v_ids, 1), 0);
  if n = 0 then
    -- Equipe vide (tout le monde a quitte) : on cloture la manche proprement.
    perform public._tf_end_round(p_game_id, v_game.control_team, false);
    return;
  end if;

  -- Rotation pour que le gagnant du face-a-face joue le premier.
  for i in 1..n loop
    if v_ids[i] = v_game.buzz_winner then v_start := i; end if;
  end loop;
  for i in 0..(n - 1) loop
    v_order := array_append(v_order, v_ids[((v_start - 1 + i) % n) + 1]);
  end loop;

  update public.tf_games
     set turn_order       = v_order,
         turn_index       = 0,
         active_player_id = v_order[1]
   where id = p_game_id;                                 -- WHERE obligatoire

  perform public._tf_phase(p_game_id, 'TEAM_TURN', 'team_turn',
    jsonb_build_object('player', v_order[1], 'team', v_game.control_team,
                       'turnIndex', 0),
    greatest(1000, v_game.team_ms_left));
end;
$$;

-- Passe la main au joueur suivant : rotation STRICTE, y compris apres une
-- mauvaise reponse. Celui qui s'est trompe ne rejoue pas tout de suite.
create or replace function public._tf_next_turn(p_game_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_game public.tf_games;
  n      integer;
  v_idx  integer;
  v_pid  uuid;
  i      integer;
begin
  select * into v_game from public.tf_games where id = p_game_id;
  n := coalesce(array_length(v_game.turn_order, 1), 0);
  if n = 0 then
    perform public._tf_begin_team_turn(p_game_id);
    return;
  end if;

  -- On saute les joueurs deconnectes, sans jamais boucler indefiniment.
  v_idx := v_game.turn_index;
  for i in 1..n loop
    v_idx := (v_idx + 1) % n;
    v_pid := v_game.turn_order[v_idx + 1];
    if exists (select 1 from public.tf_players
                where id = v_pid and game_id = p_game_id
                  and connected
                  and last_seen > now() - public._tf_live_window()) then
      exit;
    end if;
  end loop;

  update public.tf_games
     set turn_index = v_idx, active_player_id = v_pid
   where id = p_game_id;                                 -- WHERE obligatoire

  perform public._tf_phase(p_game_id, 'TEAM_TURN', 'team_turn',
    jsonb_build_object('player', v_pid, 'team', v_game.control_team,
                       'turnIndex', v_idx),
    greatest(1000, v_game.team_ms_left));
end;
$$;

