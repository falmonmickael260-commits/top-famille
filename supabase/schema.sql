-- Les questions du panel. JAMAIS lisibles par un client (voir section RLS) :
-- sinon il suffirait d'ouvrir les DevTools pour connaitre les reponses.
create table if not exists public.tf_questions (
  id            integer primary key,
  prompt        text not null,
  category      text not null,
  difficulty    integer not null default 1,
  -- Provenance. source_type = 'panel' : bareme editorial du jeu, affiche
  -- "PANEL TOP FAMILLE". source_type = 'survey' : vraie enquete publiee,
  -- et dans ce cas source_url / source_date / population sont obligatoires.
  source_type   text not null default 'panel'
                  check (source_type in ('panel', 'survey')),
  source_label  text not null default 'Panel TOP FAMILLE',
  source_url    text,
  source_date   date,
  population    text,
  country       text not null default 'FR',
  sample_size   integer not null default 100,
  constraint tf_questions_survey_needs_source
    check (source_type <> 'survey'
           or (source_url is not null and source_date is not null
               and population is not null))
);

create table if not exists public.tf_answers (
  id           bigint primary key generated by default as identity,
  question_id  integer not null references public.tf_questions(id) on delete cascade,
  rank         integer not null check (rank between 1 and 8),
  label        text not null,
  points       integer not null check (points > 0),
  -- Formes acceptees, deja normalisees par _tf_norm au moment du seed.
  accepted     text[] not null default '{}',
  unique (question_id, rank)
);

create index if not exists tf_answers_question_idx on public.tf_answers (question_id);

create table if not exists public.tf_games (
  id                 uuid primary key default gen_random_uuid(),
  code               text unique not null,
  status             text not null default 'lobby'
                       check (status in ('lobby', 'playing', 'finished')),

  -- La machine d'etat. phase_seq s'incremente a CHAQUE changement : c'est
  -- lui qui rend tf_tick() idempotent et qui sert de cle d'animation au TV.
  phase              text not null default 'LOBBY'
                       check (phase in (
                         'LOBBY', 'INTRO', 'FACE_OFF', 'BUZZING', 'ANSWERING',
                         'CORRECT_ANSWER', 'WRONG_ANSWER', 'CONTROL_GRANTED',
                         'TEAM_TURN', 'THREE_STRIKES', 'STEAL', 'STEAL_RESULT',
                         'ROUND_RESULT', 'ROUND_TRANSITION', 'FINALE_INTRO',
                         'FINALE_PLAYER_ONE', 'FINALE_PLAYER_TWO',
                         'FINALE_REVEAL', 'VICTORY')),
  phase_seq          integer not null default 0,
  phase_started_at   timestamptz not null default now(),
  phase_ends_at      timestamptz,

  round_number       integer not null default 0,
  round_multiplier   integer not null default 1,
  question_id        integer references public.tf_questions(id) on delete set null,
  used_question_ids  integer[] not null default '{}',
  round_points       integer not null default 0,

  control_team       text check (control_team in ('R', 'B')),
  strikes            integer not null default 0,
  score_r            integer not null default 0,
  score_b            integer not null default 0,

  host_player_id     uuid,

  -- Face-a-face
  faceoff_r          uuid,
  faceoff_b          uuid,
  faceoff_tried      uuid[] not null default '{}',
  buzz_winner        uuid,
  buzz_at            timestamptz,

  -- Tour d'equipe : rotation stricte, un joueur apres l'autre
  turn_order         uuid[] not null default '{}',
  turn_index         integer not null default 0,
  active_player_id   uuid,
  -- Chrono d'equipe mis en pause pendant les beats CORRECT_/WRONG_ANSWER.
  team_ms_left       integer not null default 0,

  -- Vol de manche : une seule tentative, verrouillee cote serveur
  steal_team         text check (steal_team in ('R', 'B')),
  steal_by           uuid,
  steal_answer_id    bigint,
  steal_raw          text,
  steal_success      boolean,

  -- Finale
  finale_team        text check (finale_team in ('R', 'B')),
  finale_p1          uuid,
  finale_p2          uuid,
  finale_question_ids integer[] not null default '{}',
  finale_slot        integer not null default 0,
  finale_q_index     integer not null default 0,
  finale_reveal_step integer not null default 0,
  finale_total       integer not null default 0,

  winner_team        text check (winner_team in ('R', 'B', 'TIE')),

  last_event         jsonb,
  last_event_at      timestamptz,
  created_at         timestamptz not null default now()
);

create table if not exists public.tf_players (
  id             uuid primary key,             -- = auth.uid() (Anonymous Sign-In)
  game_id        uuid references public.tf_games(id) on delete set null,
  name           text not null,
  team           text not null check (team in ('R', 'B')),
  connected      boolean not null default true,
  -- Nombre de face-a-face deja joues : sert a equilibrer les participations.
  faceoff_count  integer not null default 0,
  -- Battement de coeur : le client rappelle tf_state toutes les 15 s. Un
  -- telephone verrouille redevient "vivant" des qu'on le rallume, sans que
  -- le joueur ait a rejoindre quoi que ce soit.
  last_seen      timestamptz not null default now(),
  joined_at      timestamptz not null default now(),  -- ordre de rotation
  created_at     timestamptz not null default now()
);

alter table public.tf_players
  add column if not exists last_seen timestamptz not null default now();

