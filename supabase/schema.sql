create or replace function public.tf_create(p_code text, p_name text, p_team text)
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid  uuid;
  v_code text;
  v_name text;
  v_team text;
  v_id   uuid;
begin
  v_uid  := public._tf_uid();
  v_code := upper(btrim(coalesce(p_code, '')));
  v_name := left(btrim(coalesce(p_name, '')), 18);
  v_team := upper(btrim(coalesce(p_team, 'R')));

  if v_name = '' then
    raise exception 'Choisis un pseudo.' using errcode = 'P0001';
  end if;
  if v_team not in ('R', 'B') then v_team := 'R'; end if;
  if v_code !~ '^[A-Z0-9]{4,6}$' then
    raise exception 'Code de partie invalide.' using errcode = 'P0001';
  end if;
  if exists (select 1 from public.tf_games where code = v_code) then
    raise exception 'Ce code de partie est deja utilise.' using errcode = 'P0001';
  end if;

  insert into public.tf_games (code) values (v_code) returning id into v_id;

  insert into public.tf_players (id, game_id, name, team, connected, faceoff_count, joined_at)
       values (v_uid, v_id, v_name, v_team, true, 0, now())
  on conflict (id) do update
     set game_id = excluded.game_id,
         name = excluded.name,
         team = excluded.team,
         connected = true,
         faceoff_count = 0,
         joined_at = now();

  update public.tf_games set host_player_id = v_uid
   where id = v_id;                                      -- WHERE obligatoire

  return public._tf_state(v_id, v_uid);
end;
$$;

create or replace function public.tf_join(p_code text, p_name text, p_team text)
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid  uuid;
  v_name text;
  v_team text;
  v_game public.tf_games;
  v_n    integer;
begin
  v_uid  := public._tf_uid();
  v_name := left(btrim(coalesce(p_name, '')), 18);
  v_team := upper(btrim(coalesce(p_team, '')));
  v_game := public._tf_game(p_code);

  if v_name = '' then
    raise exception 'Choisis un pseudo.' using errcode = 'P0001';
  end if;
  if v_team not in ('R', 'B') then
    raise exception 'Equipe invalide.' using errcode = 'P0001';
  end if;

  -- Partie deja lancee : seul un joueur deja inscrit peut revenir
  -- (rechargement de page, changement de reseau, telephone verrouille).
  if v_game.status <> 'lobby' then
    if not exists (select 1 from public.tf_players
                    where id = v_uid and game_id = v_game.id) then
      raise exception 'Le show a deja commence' using errcode = 'P0001';
    end if;
    update public.tf_players set connected = true
     where id = v_uid and game_id = v_game.id;           -- WHERE obligatoire
    return public._tf_state(v_game.id, v_uid);
  end if;

  -- Verrou sur la partie : compter puis inserer ne sont pas atomiques, et
  -- dans un salon deux personnes appuient sur "Rejoindre" en meme temps.
  -- Sans ce verrou les deux lisaient 5, les deux passaient, et l'equipe se
  -- retrouvait a 7 alors que la limite est de 6.
  perform 1 from public.tf_games where id = v_game.id for update;

  select count(*) into v_n from public.tf_players
   where game_id = v_game.id and team = v_team and id <> v_uid;
  if v_n >= public.tf_max_per_team() then
    raise exception 'Cette equipe est complete' using errcode = 'P0001';
  end if;

  insert into public.tf_players (id, game_id, name, team, connected, faceoff_count, joined_at)
       values (v_uid, v_game.id, v_name, v_team, true, 0, now())
  on conflict (id) do update
     set game_id = excluded.game_id,
         name = excluded.name,
         team = excluded.team,
         connected = true,
         faceoff_count = case when tf_players.game_id is distinct from excluded.game_id
                              then 0 else tf_players.faceoff_count end,
         joined_at = case when tf_players.game_id is distinct from excluded.game_id
                          then now() else tf_players.joined_at end;

  perform public._tf_event(v_game.id, 'player_joined',
    jsonb_build_object('player', v_uid, 'name', v_name, 'team', v_team));

  return public._tf_state(v_game.id, v_uid);
end;
$$;

create or replace function public.tf_set_team(p_code text, p_team text)
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid  uuid;
  v_team text;
  v_game public.tf_games;
  v_n    integer;
begin
  v_uid  := public._tf_uid();
  v_team := upper(btrim(coalesce(p_team, '')));
  v_game := public._tf_game(p_code);

  if v_game.status <> 'lobby' then
    raise exception 'On ne change plus d''equipe une fois le show lance.'
      using errcode = 'P0001';
  end if;
  if v_team not in ('R', 'B') then
    raise exception 'Equipe invalide.' using errcode = 'P0001';
  end if;

  -- Meme course que dans tf_join : deux bascules simultanees vers la meme
  -- equipe pouvaient la faire deborder. On serialise par partie.
  perform 1 from public.tf_games where id = v_game.id for update;

  select count(*) into v_n from public.tf_players
   where game_id = v_game.id and team = v_team and id <> v_uid;
  if v_n >= public.tf_max_per_team() then
    raise exception 'Cette equipe est complete' using errcode = 'P0001';
  end if;

  update public.tf_players set team = v_team
   where id = v_uid and game_id = v_game.id;             -- WHERE obligatoire

  return public._tf_state(v_game.id, v_uid);
end;
$$;

create or replace function public.tf_start(p_code text)
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid  uuid;
  v_game public.tf_games;
  n_r integer;
  n_b integer;
begin
  v_uid  := public._tf_uid();
  v_game := public._tf_game(p_code);

  if v_game.host_player_id is distinct from v_uid then
    raise exception 'Seul l''hote peut lancer le show.' using errcode = 'P0001';
  end if;
  if v_game.status = 'playing' then
    return public._tf_state(v_game.id, v_uid);           -- idempotent
  end if;

  select count(*) filter (where team = 'R'),
         count(*) filter (where team = 'B')
    into n_r, n_b
    from public.tf_players where game_id = v_game.id;

  if n_r = 0 or n_b = 0 then
    raise exception 'Il faut au moins un joueur dans chaque equipe.'
      using errcode = 'P0001';
  end if;

  delete from public.tf_reveals where game_id = v_game.id;
  delete from public.tf_finale_answers where game_id = v_game.id;

  update public.tf_games
     set status = 'playing', score_r = 0, score_b = 0,
         round_number = 0, round_points = 0, strikes = 0,
         used_question_ids = '{}', question_id = null,
         control_team = null, winner_team = null,
         finale_total = 0, finale_slot = 0, finale_q_index = 0,
         finale_reveal_step = 0, finale_question_ids = '{}',
         finale_team = null, finale_p1 = null, finale_p2 = null
   where id = v_game.id;                                 -- WHERE obligatoire

  update public.tf_players set faceoff_count = 0
   where game_id = v_game.id;                            -- WHERE obligatoire

  perform public._tf_phase(v_game.id, 'INTRO', 'intro',
    jsonb_build_object('rounds', public.tf_rounds()));

  return public._tf_state(v_game.id, v_uid);
end;
$$;

-- LE BUZZER. C'est le serveur qui decide qui a buzze en premier : le
-- premier UPDATE qui trouve buzz_winner is null gagne, les autres voient
-- row_count = 0. Deux buzz a la milliseconde ne peuvent pas passer tous
-- les deux, meme depuis deux telephones sur deux reseaux differents.
create or replace function public.tf_buzz(p_code text)
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid  uuid;
  v_game public.tf_games;
  v_rows integer;
begin
  v_uid  := public._tf_uid();
  v_game := public._tf_game(p_code);
  perform public._tf_touch(v_uid, v_game.id);

  -- L'identite d'abord : un joueur qui n'est pas sur le duel doit etre
  -- refuse, que la fenetre de buzz soit ouverte ou deja fermee.
  if v_uid is distinct from v_game.faceoff_r
     and v_uid is distinct from v_game.faceoff_b then
    raise exception 'Tu n''es pas sur le face-a-face.' using errcode = 'P0001';
  end if;
  if v_game.phase <> 'BUZZING' then
    return public._tf_state(v_game.id, v_uid);           -- trop tard, ou trop tot
  end if;

  update public.tf_games
     set buzz_winner = v_uid, buzz_at = now()
   where id = v_game.id
     and phase = 'BUZZING'
     and buzz_winner is null
     and phase_seq = v_game.phase_seq;                   -- WHERE obligatoire
  get diagnostics v_rows = row_count;

  if v_rows = 0 then
    return public._tf_state(v_game.id, v_uid);           -- l'autre a ete plus rapide
  end if;

  perform public._tf_phase(v_game.id, 'ANSWERING', 'buzz',
    jsonb_build_object('player', v_uid,
                       'team', case when v_uid = v_game.faceoff_r then 'R' else 'B' end));

  return public._tf_state(v_game.id, v_uid);
end;
$$;

-- LA VALIDATION D'UNE REPONSE. Un seul point d'entree pour les quatre
-- situations ou un joueur peut repondre : face-a-face, tour d'equipe,
-- vol de manche, finale. Le serveur verifie a chaque fois que c'est bien
-- a l'appelant de parler, et le "phase_seq" empeche le double-clic.
create or replace function public.tf_submit(p_code text, p_raw text)
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid   uuid;
  v_game  public.tf_games;
  v_raw   text;
  v_aid   bigint;
  v_rows  integer;
  v_team  text;
  v_left  integer;
  v_award integer;
  v_lbl   text;
  v_pts   integer;
  v_rank  integer;
  v_seen  boolean;
begin
  v_uid  := public._tf_uid();
  v_game := public._tf_game(p_code);
  v_raw  := left(btrim(coalesce(p_raw, '')), 60);
  perform public._tf_touch(v_uid, v_game.id);

  select team into v_team from public.tf_players
   where id = v_uid and game_id = v_game.id;
  if v_team is null then
    raise exception 'Tu n''es pas dans cette partie.' using errcode = 'P0001';
  end if;
  if v_raw = '' then
    raise exception 'Ecris une reponse.' using errcode = 'P0001';
  end if;

  -- Temps restant sur le chrono d'equipe, mesure AVANT de consommer la phase.
  v_left := greatest(0, floor(extract(epoch from
              (coalesce(v_game.phase_ends_at, now()) - now())) * 1000))::integer;

  /* ---------------- FACE-A-FACE ---------------- */
  if v_game.phase = 'ANSWERING' then
    if v_uid is distinct from v_game.buzz_winner then
      raise exception 'Ce n''est pas a toi de repondre.' using errcode = 'P0001';
    end if;

    -- Verrou anti double-clic : on consomme la phase.
    update public.tf_games set phase_ends_at = null
     where id = v_game.id and phase_seq = v_game.phase_seq
       and phase = 'ANSWERING';                          -- WHERE obligatoire
    get diagnostics v_rows = row_count;
    if v_rows = 0 then return public._tf_state(v_game.id, v_uid); end if;

    v_aid := public._tf_match(v_game.question_id, v_raw);

    if v_aid is null then
      update public.tf_games
         set faceoff_tried = array_append(faceoff_tried, v_uid)
       where id = v_game.id;                             -- WHERE obligatoire
      perform public._tf_phase(v_game.id, 'WRONG_ANSWER', 'wrong_answer',
        jsonb_build_object('scope', 'faceoff', 'player', v_uid,
                           'team', v_team, 'raw', v_raw));
    else
      select label, points, rank into v_lbl, v_pts, v_rank
        from public.tf_answers where id = v_aid;
      v_award := public._tf_reveal(v_game.id, v_aid, v_team, v_uid);
      perform public._tf_phase(v_game.id, 'CORRECT_ANSWER', 'correct_answer',
        jsonb_build_object('scope', 'faceoff', 'player', v_uid, 'team', v_team,
                           'raw', v_raw, 'answerId', v_aid, 'rank', v_rank,
                           'label', v_lbl, 'points', v_pts, 'awarded', v_award));
    end if;
    return public._tf_state(v_game.id, v_uid);
  end if;

  /* ---------------- TOUR D'EQUIPE ---------------- */
  if v_game.phase = 'TEAM_TURN' then
    if v_uid is distinct from v_game.active_player_id then
      raise exception 'Attends ton tour.' using errcode = 'P0001';
    end if;

    update public.tf_games set phase_ends_at = null
     where id = v_game.id and phase_seq = v_game.phase_seq
       and phase = 'TEAM_TURN';                          -- WHERE obligatoire
    get diagnostics v_rows = row_count;
    if v_rows = 0 then return public._tf_state(v_game.id, v_uid); end if;

    -- Le chrono d'equipe est commun a la phase : on le met en pause le temps
    -- de l'animation, et il reprendra la ou il en etait.
    update public.tf_games set team_ms_left = v_left
     where id = v_game.id;                               -- WHERE obligatoire

    v_aid := public._tf_match(v_game.question_id, v_raw);

    if v_aid is null then
      update public.tf_games set strikes = strikes + 1
       where id = v_game.id;                             -- WHERE obligatoire
      perform public._tf_phase(v_game.id, 'WRONG_ANSWER', 'wrong_answer',
        jsonb_build_object('scope', 'team', 'player', v_uid, 'team', v_team,
                           'raw', v_raw,
                           'strikes', v_game.strikes + 1));
      return public._tf_state(v_game.id, v_uid);
    end if;

    select exists (select 1 from public.tf_reveals
                    where game_id = v_game.id
                      and round_number = v_game.round_number
                      and answer_id = v_aid)
      into v_seen;

    select label, points, rank into v_lbl, v_pts, v_rank
      from public.tf_answers where id = v_aid;

    if v_seen then
      -- Reponse deja sur le tableau : tour perdu, mais pas de faute. Le
      -- chrono continue de tourner, donc rien a gagner a le faire expres.
      perform public._tf_phase(v_game.id, 'WRONG_ANSWER', 'already_found',
        jsonb_build_object('scope', 'team', 'player', v_uid, 'team', v_team,
                           'raw', v_raw, 'label', v_lbl, 'rank', v_rank,
                           'alreadyFound', true, 'strikes', v_game.strikes));
    else
      v_award := public._tf_reveal(v_game.id, v_aid, v_team, v_uid);
      perform public._tf_phase(v_game.id, 'CORRECT_ANSWER', 'correct_answer',
        jsonb_build_object('scope', 'team', 'player', v_uid, 'team', v_team,
                           'raw', v_raw, 'answerId', v_aid, 'rank', v_rank,
                           'label', v_lbl, 'points', v_pts, 'awarded', v_award,
                           'cleared', public._tf_hidden_left(v_game.id) = 0));
    end if;
    return public._tf_state(v_game.id, v_uid);
  end if;

  /* ---------------- VOL DE MANCHE ---------------- */
  if v_game.phase = 'STEAL' then
    if v_team is distinct from v_game.steal_team then
      raise exception 'Le vol est a l''autre equipe.' using errcode = 'P0001';
    end if;

    -- UNE SEULE tentative pour toute l'equipe : le premier a valider
    -- verrouille, les autres n'ont plus la main.
    update public.tf_games
       set steal_by = v_uid, steal_raw = v_raw, phase_ends_at = null
     where id = v_game.id and phase = 'STEAL' and steal_by is null
       and phase_seq = v_game.phase_seq;                 -- WHERE obligatoire
    get diagnostics v_rows = row_count;
    if v_rows = 0 then return public._tf_state(v_game.id, v_uid); end if;

    v_aid := public._tf_match(v_game.question_id, v_raw);
    select exists (select 1 from public.tf_reveals
                    where game_id = v_game.id
                      and round_number = v_game.round_number
                      and answer_id = v_aid)
      into v_seen;

    -- Une reponse deja affichee ne vole rien : il faut en trouver une neuve.
    if v_aid is null or v_seen then
      update public.tf_games set steal_success = false, steal_answer_id = null
       where id = v_game.id;                             -- WHERE obligatoire
      perform public._tf_phase(v_game.id, 'STEAL_RESULT', 'steal_result',
        jsonb_build_object('success', false, 'team', v_game.steal_team,
                           'player', v_uid, 'raw', v_raw,
                           'alreadyFound', coalesce(v_seen, false),
                           'points', v_game.round_points));
    else
      select label, points, rank into v_lbl, v_pts, v_rank
        from public.tf_answers where id = v_aid;
      v_award := public._tf_reveal(v_game.id, v_aid, v_game.steal_team, v_uid);
      update public.tf_games set steal_success = true, steal_answer_id = v_aid
       where id = v_game.id;                             -- WHERE obligatoire
      perform public._tf_phase(v_game.id, 'STEAL_RESULT', 'steal_result',
        jsonb_build_object('success', true, 'team', v_game.steal_team,
                           'player', v_uid, 'raw', v_raw, 'answerId', v_aid,
                           'rank', v_rank, 'label', v_lbl,
                           'answerPoints', v_pts, 'awarded', v_award,
                           'points', (select round_points from public.tf_games
                                       where id = v_game.id),
                           'from', v_game.control_team));
    end if;
    return public._tf_state(v_game.id, v_uid);
  end if;

  /* ---------------- FINALE ---------------- */
  if v_game.phase in ('FINALE_PLAYER_ONE', 'FINALE_PLAYER_TWO') then
    if (v_game.finale_slot = 1 and v_uid is distinct from v_game.finale_p1)
       or (v_game.finale_slot = 2 and v_uid is distinct from v_game.finale_p2) then
      raise exception 'Ce n''est pas a toi de repondre.' using errcode = 'P0001';
    end if;

    update public.tf_games set phase_ends_at = null
     where id = v_game.id and phase_seq = v_game.phase_seq;  -- WHERE obligatoire
    get diagnostics v_rows = row_count;
    if v_rows = 0 then return public._tf_state(v_game.id, v_uid); end if;

    perform public._tf_finale_record(v_game.id, v_game.finale_slot,
                                     v_game.finale_q_index, v_raw, false);
    return public._tf_state(v_game.id, v_uid);
  end if;

  raise exception 'Ce n''est pas le moment de repondre.' using errcode = 'P0001';
end;
$$;

-- Avance la machine quand un chrono a expire. Appelable par tous les
-- clients ; un seul appel fait effet (voir _tf_tick).
create or replace function public.tf_tick(p_code text)
returns json
