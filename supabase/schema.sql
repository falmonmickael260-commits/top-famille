-- Commande technique de l'hote : forcer la phase en cours a expirer
-- maintenant, pour que le tick suivant enchaine. Sert quand un joueur a
-- ferme son telephone en plein tour et que le show attend pour rien.
-- L'hote ne peut QUE accelerer : il ne choisit ni la suite, ni le gagnant.
create or replace function public.tf_host_skip(p_code text)
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid  uuid;
  v_game public.tf_games;
begin
  v_uid  := public._tf_uid();
  v_game := public._tf_game(p_code);

  if v_game.host_player_id is distinct from v_uid then
    raise exception 'Seul l''hote peut passer la phase.' using errcode = 'P0001';
  end if;
  if v_game.status <> 'playing' or v_game.phase_ends_at is null then
    return public._tf_state(v_game.id, v_uid);
  end if;

  update public.tf_games set phase_ends_at = now()
   where id = v_game.id and phase_seq = v_game.phase_seq;  -- WHERE obligatoire

  perform public._tf_tick(v_game.id);
  return public._tf_state(v_game.id, v_uid);
end;
$$;

create or replace function public.tf_state(p_code text)
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid  uuid;
  v_game public.tf_games;
begin
  v_uid  := public._tf_uid();
  v_game := public._tf_game(p_code);

  -- Battement de coeur. Un joueur qui revient (onglet re-ouvert, telephone
  -- deverrouille, reseau retabli) se remet en ligne tout seul.
  perform public._tf_touch(v_uid, v_game.id);

  return public._tf_state(v_game.id, v_uid);
end;
$$;

create or replace function public.tf_leave(p_code text)
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid  uuid;
  v_game public.tf_games;
  v_new  uuid;
begin
  v_uid  := public._tf_uid();
  v_game := public._tf_game(p_code);

  if v_game.status = 'lobby' then
    -- Dans le lobby, quitter veut dire partir pour de bon.
    update public.tf_players set game_id = null, connected = false
     where id = v_uid and game_id = v_game.id;           -- WHERE obligatoire
  else
    -- En cours de show, on reste dans l'equipe (la rotation en a besoin),
    -- on est juste marque hors ligne : le jeu saute notre tour.
    update public.tf_players set connected = false
     where id = v_uid and game_id = v_game.id;           -- WHERE obligatoire
  end if;

  -- L'hote part : on passe la main au joueur present depuis le plus longtemps.
  if v_game.host_player_id = v_uid then
    select id into v_new from public.tf_players
     where game_id = v_game.id and id <> v_uid
       and connected and last_seen > now() - public._tf_live_window()
     order by joined_at, id limit 1;
    if v_new is null then
      select id into v_new from public.tf_players
       where game_id = v_game.id and id <> v_uid
       order by joined_at, id limit 1;
    end if;
    update public.tf_games set host_player_id = v_new
     where id = v_game.id;                              -- WHERE obligatoire
  end if;

  perform public._tf_event(v_game.id, 'player_left',
    jsonb_build_object('player', v_uid));

  return public._tf_state(v_game.id, v_uid);
end;
$$;

create or replace function public.tf_restart(p_code text)
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid  uuid;
  v_game public.tf_games;
begin
  v_uid  := public._tf_uid();
  v_game := public._tf_game(p_code);

  if v_game.host_player_id is distinct from v_uid then
    raise exception 'Seul l''hote peut relancer le show.' using errcode = 'P0001';
  end if;

  delete from public.tf_reveals where game_id = v_game.id;
  delete from public.tf_finale_answers where game_id = v_game.id;
  delete from public.tf_events where game_id = v_game.id;

  update public.tf_games
     set status = 'lobby', phase = 'LOBBY', phase_seq = phase_seq + 1,
         phase_started_at = now(), phase_ends_at = null,
         round_number = 0, round_multiplier = 1, round_points = 0,
         question_id = null, used_question_ids = '{}',
         control_team = null, strikes = 0, score_r = 0, score_b = 0,
         faceoff_r = null, faceoff_b = null, faceoff_tried = '{}',
         buzz_winner = null, buzz_at = null,
         turn_order = '{}', turn_index = 0, active_player_id = null,
         team_ms_left = 0,
         steal_team = null, steal_by = null, steal_answer_id = null,
         steal_raw = null, steal_success = null,
         finale_team = null, finale_p1 = null, finale_p2 = null,
         finale_question_ids = '{}', finale_slot = 0, finale_q_index = 0,
         finale_reveal_step = 0, finale_total = 0,
         winner_team = null, last_event = null, last_event_at = null
   where id = v_game.id;                                 -- WHERE obligatoire

  update public.tf_players set faceoff_count = 0
   where game_id = v_game.id;                            -- WHERE obligatoire

  return public._tf_state(v_game.id, v_uid);
end;
$$;

