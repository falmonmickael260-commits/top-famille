-- Duree de chaque phase, en secondes. NULL = pas de chrono (on attend une
-- action, ou c'est la fin de la partie).
create or replace function public.tf_phase_seconds(p_phase text)
returns integer language sql immutable as $$
  select case p_phase
    when 'INTRO'             then 9
    when 'FACE_OFF'          then 5
    when 'BUZZING'           then 12
    -- 10 s etaient trop courtes pour ecrire sur un telephone : le temps de
    -- voir la question, de reflechir et de taper, le chrono etait passe.
    when 'ANSWERING'         then 15
    when 'CORRECT_ANSWER'    then 3
    when 'WRONG_ANSWER'      then 3
    when 'CONTROL_GRANTED'   then 4
    -- Temps COMMUN a toute l'equipe, mis en pause pendant les animations.
    -- Porte de 25 a 35 s : a trois ou quatre joueurs qui passent chacun leur
    -- tour, 25 s laissaient a peine le temps d'une reponse par personne.
    when 'TEAM_TURN'         then 35
    when 'THREE_STRIKES'     then 4
    when 'STEAL'             then 25
    when 'STEAL_RESULT'      then 5
    when 'ROUND_RESULT'      then 9
    when 'ROUND_TRANSITION'  then 5
    when 'FINALE_INTRO'      then 7
    when 'FINALE_PLAYER_ONE' then 25
    when 'FINALE_PLAYER_TWO' then 25
    when 'FINALE_REVEAL'     then 4
    else null
  end
$$;

-- ---------------------------------------------------------------------
-- 3. NORMALISATION ET COMPARAISON DES REPONSES
--    Le joueur tape au telephone, vite, sans accents, avec des fautes.
--    Tout est compare ici, cote serveur.
-- ---------------------------------------------------------------------

-- Minuscules, accents retires, ponctuation retiree, articles de tete
-- retires, espaces normalises. Volontairement sans extension (pas de
-- dependance a unaccent) pour que ce fichier s'execute partout.
create or replace function public._tf_norm(p_text text)
returns text
language plpgsql
immutable
as $$
declare
  v text;
begin
  v := lower(coalesce(p_text, ''));
  -- Les ligatures d'abord : translate() ne fait que du 1 caractere vers 1
  -- caractere, il transformerait « oeuf » en « ouf ».
  v := replace(v, 'œ', 'oe');
  v := replace(v, 'æ', 'ae');
  v := translate(v,
        'àáâãäåçèéêëìíîïñòóôõöùúûüýÿ',
        'aaaaaaceeeeiiiinooooouuuuyy');
  -- L'apostrophe devient un espace : "l'eau" -> "l eau" -> article retire.
  v := regexp_replace(v, '[^a-z0-9]+', ' ', 'g');
  v := btrim(regexp_replace(v, '\s+', ' ', 'g'));
  -- Articles et petites prepositions en tete, retires en boucle :
  -- "de la creme solaire" -> "creme solaire".
  for i in 1..3 loop
    v := regexp_replace(
           v,
           '^(le|la|les|l|un|une|des|du|de|d|au|aux|a|mon|ma|mes|son|sa|ses|leur|leurs|the)\s+',
           '');
  end loop;
  return btrim(v);
end;
$$;

-- Distance de Levenshtein, en plpgsql pur : tolere les fautes de frappe
-- sans dependre de l'extension fuzzystrmatch.
create or replace function public._tf_lev(a text, b text)
returns integer
language plpgsql
immutable
as $$
declare
  la integer := length(a);
  lb integer := length(b);
  prev integer[];
  cur  integer[];
  i integer;
  j integer;
  cost integer;
begin
  if la = 0 then return lb; end if;
  if lb = 0 then return la; end if;
  -- Garde-fou : au-dela, la comparaison n'a plus de sens pour un mot tape.
  if abs(la - lb) > 4 then return abs(la - lb); end if;

  prev := array(select generate_series(0, lb));
  for i in 1..la loop
    cur := array_fill(0, array[lb + 1]);
    cur[1] := i;
    for j in 1..lb loop
      cost := case when substr(a, i, 1) = substr(b, j, 1) then 0 else 1 end;
      cur[j + 1] := least(cur[j] + 1, prev[j + 1] + 1, prev[j] + cost);
    end loop;
    prev := cur;
  end loop;
  return prev[lb + 1];
end;
$$;

-- Deux formes normalisees decrivent-elles la meme reponse ?
--   - egalite stricte
--   - pluriel / singulier ("serviettes" = "serviette")
--   - une faute de frappe sur un mot assez long
-- On reste volontairement severe : une tolerance trop large accepterait
-- des reponses qui changent le sens, ce qui ruinerait le jeu.
create or replace function public._tf_same(p_try text, p_ref text)
returns boolean
language plpgsql
immutable
as $$
declare
  a text := p_try;
  b text := p_ref;
  la integer;
  d integer;
begin
  if a = '' or b = '' then return false; end if;
  if a = b then return true; end if;

  -- pluriel simple, des deux cotes
  if rtrim(a, 's') = rtrim(b, 's') and length(rtrim(a, 's')) >= 3 then
    return true;
  end if;

  la := length(b);
  if la < 5 then
    return false;              -- trop court : une lettre change le mot
  end if;

  d := public._tf_lev(a, b);
  if la >= 9 then
    return d <= 2;
  end if;
  return d <= 1;
end;
$$;

-- Cherche la reponse du sondage correspondant a ce que le joueur a tape.
-- Renvoie l'id de la reponse, ou NULL. Le client ne voit jamais la liste :
-- il envoie une chaine, le serveur repond trouve / pas trouve.
create or replace function public._tf_match(p_question_id integer, p_raw text)
returns bigint
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_try text := public._tf_norm(p_raw);
  r record;
  f text;
  w text;
begin
  if v_try = '' then return null; end if;

  -- 1. Correspondance sur le libelle ou une forme acceptee.
  for r in
    select id, public._tf_norm(label) as nlabel, accepted
      from public.tf_answers
     where question_id = p_question_id
     order by rank
  loop
    if public._tf_same(v_try, r.nlabel) then
      return r.id;
    end if;
    foreach f in array r.accepted loop
      if public._tf_same(v_try, public._tf_norm(f)) then
        return r.id;
      end if;
    end loop;
  end loop;

  -- 2. Le joueur a fait une phrase ("je dirais une serviette de plage").
  --    On accepte si une forme d'un seul mot, assez longue, apparait comme
  --    mot entier dans sa reponse. Pas de sous-chaine : "car" ne doit pas
  --    valider "carotte".
  for r in
    select id, public._tf_norm(label) as nlabel, accepted
      from public.tf_answers
     where question_id = p_question_id
     order by rank
  loop
    foreach f in array (array[r.nlabel]
                        || array(select public._tf_norm(t.v)
                                   from unnest(r.accepted) as t(v)))
    loop
      if f <> '' and position(' ' in f) = 0 and length(f) >= 5 then
        foreach w in array string_to_array(v_try, ' ') loop
          if public._tf_same(w, f) then
            return r.id;
          end if;
        end loop;
      end if;
    end loop;
  end loop;

  return null;
end;
$$;

