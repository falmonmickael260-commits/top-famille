-- 9. ROW LEVEL SECURITY
--
--   Lecture libre sur tf_games / tf_players / tf_events : le Realtime en
--   depend, et ces lignes ne contiennent aucune reponse (uniquement des
--   scores, des ids, des phases et des chronos).
--
--   AUCUNE ecriture directe, nulle part : tout passe par les fonctions
--   SECURITY DEFINER ci-dessus. Un joueur ne peut donc pas s'attribuer des
--   points, se declarer joueur actif, se donner le buzz ou rallonger son
--   chrono, meme en appelant l'API REST a la main.
