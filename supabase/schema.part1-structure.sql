-- Prepare la finale : l'equipe en tete, deux joueurs, cinq questions.
create or replace function public._tf_begin_finale(p_game_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_game public.tf_games;
  v_team text;
  v_ids  uuid[];
  v_qs   integer[];
begin
  select * into v_game from public.tf_games where id = p_game_id;

  if v_game.score_r > v_game.score_b then
    v_team := 'R';
  elsif v_game.score_b > v_game.score_r then
    v_team := 'B';
  else
    v_team := coalesce(v_game.control_team, 'R');   -- egalite parfaite
  end if;

  -- Les joueurs encore en ligne d'abord : ce sont eux qui pourront repondre.
  select array_agg(id order by faceoff_count desc, joined_at, id) into v_ids
    from public.tf_players
   where game_id = p_game_id and team = v_team
     and connected and last_seen > now() - public._tf_live_window();

  -- Puis on complete avec le reste de l'equipe. Sans ce rattrapage, un seul
  -- coequipier en ligne au moment de la finale suffisait a faire jouer le
  -- MEME joueur sur les deux manches — alors que ses coequipiers etaient
  -- juste en train de rallumer leur telephone. Deux joueurs differents des
  -- que l'equipe en compte deux.
  if coalesce(array_length(v_ids, 1), 0) < 2 then
    select coalesce(v_ids, '{}')
             || coalesce(array_agg(p.id order by p.faceoff_count desc, p.joined_at, p.id), '{}')
      into v_ids
      from public.tf_players p
     where p.game_id = p_game_id
       and p.team = v_team
       and not (p.id = any (coalesce(v_ids, '{}')));
  end if;

  select array_agg(id) into v_qs from (
    select q.id from public.tf_questions q
     where not (q.id = any (coalesce(v_game.used_question_ids, '{}')))
       and exists (select 1 from public.tf_answers a where a.question_id = q.id)
     order by random() limit 5
  ) s;

  update public.tf_games
     set finale_team         = v_team,
         finale_p1           = v_ids[1],
         -- Equipe a un seul joueur : il joue les deux manches de la finale.
         finale_p2           = coalesce(v_ids[2], v_ids[1]),
         finale_question_ids = coalesce(v_qs, '{}'),
         used_question_ids   = coalesce(used_question_ids, '{}') || coalesce(v_qs, '{}'),
         finale_slot         = 0,
         finale_q_index      = 0,
         finale_reveal_step  = 0,
         finale_total        = 0
   where id = p_game_id;                                 -- WHERE obligatoire

  perform public._tf_phase(p_game_id, 'FINALE_INTRO', 'finale_intro',
    jsonb_build_object('team', v_team, 'p1', v_ids[1],
                       'p2', coalesce(v_ids[2], v_ids[1]),
                       'target', public.tf_finale_target()));
end;
$$;

-- Termine la partie. La finale decide : l'equipe finaliste gagne si elle
-- atteint l'objectif, sinon la victoire passe a l'equipe adverse.
create or replace function public._tf_finish(p_game_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_game   public.tf_games;
  v_winner text;
  v_hit    boolean;
begin
  select * into v_game from public.tf_games where id = p_game_id;

  v_hit := v_game.finale_total >= public.tf_finale_target();
  if v_hit then
    v_winner := v_game.finale_team;
  else
    v_winner := public._tf_other(v_game.finale_team);
  end if;

  -- Les points de la finale rejoignent le score de l'equipe finaliste.
  if v_game.finale_team = 'R' then
    update public.tf_games set score_r = score_r + v_game.finale_total
     where id = p_game_id;                               -- WHERE obligatoire
  elsif v_game.finale_team = 'B' then
    update public.tf_games set score_b = score_b + v_game.finale_total
     where id = p_game_id;                               -- WHERE obligatoire
  end if;

  update public.tf_games
     set status = 'finished', winner_team = v_winner, active_player_id = null
   where id = p_game_id;                                 -- WHERE obligatoire

  perform public._tf_phase(p_game_id, 'VICTORY', 'victory',
    jsonb_build_object('winner', v_winner, 'finaleTeam', v_game.finale_team,
                       'finaleTotal', v_game.finale_total,
                       'target', public.tf_finale_target(),
                       'reached', v_hit));
end;
$$;

-- ---------------------------------------------------------------------
-- 6. LE PLATEAU, TEL QUE LE CLIENT A LE DROIT DE LE VOIR
--
--   VERROU : tf_questions et tf_answers ne sont lisibles par AUCUN client
--   (ni policy RLS, ni privilege SQL). Une reponse non encore devoilee
--   n'est pas masquee en CSS : elle ne quitte pas le serveur. Ouvrir les
--   DevTools ne donne rien.
-- ---------------------------------------------------------------------

create or replace function public._tf_board(p_game_id uuid)
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  v_game   public.tf_games;
  v_q      public.tf_questions;
  v_all    boolean;
  v_prompt boolean;
  v_slots  json;
begin
  select * into v_game from public.tf_games where id = p_game_id;
  if v_game.question_id is null then return null; end if;

  select * into v_q from public.tf_questions where id = v_game.question_id;
  if v_q.id is null then return null; end if;

  -- Tout est devoile a la fin de la manche : c'est le moment du "voila ce
  -- que vous avez rate", et la manche est jouee de toute facon.
  v_all := v_game.phase in ('ROUND_RESULT', 'ROUND_TRANSITION')
           or v_game.status = 'finished';

  -- La question elle-meme n'apparait qu'au moment du buzzer.
  v_prompt := v_game.phase not in ('LOBBY', 'INTRO', 'FACE_OFF');

  select json_agg(s order by s_rank) into v_slots from (
    select a.rank as s_rank,
           json_build_object(
             'rank', a.rank,
             'revealed', (r.answer_id is not null) or v_all,
             'found', r.answer_id is not null,
             'label', case when (r.answer_id is not null) or v_all
                           then a.label else null end,
             'points', case when (r.answer_id is not null) or v_all
                            then a.points else null end,
             'awarded', coalesce(r.awarded, 0),
             'team', r.team,
             'playerId', r.player_id
           ) as s
      from public.tf_answers a
      left join public.tf_reveals r
             on r.game_id = v_game.id
            and r.round_number = v_game.round_number
            and r.answer_id = a.id
     where a.question_id = v_game.question_id
  ) t;

  return json_build_object(
    'questionId',  v_q.id,
    'prompt',      case when v_prompt then v_q.prompt else null end,
    'category',    v_q.category,
    'sourceType',  v_q.source_type,
    'sourceLabel', v_q.source_label,
    'sourceUrl',   v_q.source_url,
    'sourceDate',  v_q.source_date,
    'population',  v_q.population,
    'country',     v_q.country,
    'sampleSize',  v_q.sample_size,
    'slots',       coalesce(v_slots, '[]'::json)
  );
end;
$$;

-- La finale : la reponse du joueur 1 ne doit JAMAIS arriver chez le joueur 2.
-- Chacun voit la sienne ; tout le monde voit celles deja devoilees.
create or replace function public._tf_finale(p_game_id uuid, p_uid uuid)
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  v_game  public.tf_games;
  v_items json;
  v_qs    json;
begin
  select * into v_game from public.tf_games where id = p_game_id;
  if coalesce(array_length(v_game.finale_question_ids, 1), 0) = 0 then
    return null;
  end if;

  -- Les 5 questions de la finale. Le libelle n'apparait que quand la
  -- question est effectivement posee, ou pendant la revelation.
  select json_agg(x order by idx) into v_qs from (
    select i - 1 as idx,
           json_build_object(
             'index', i - 1,
             'prompt', case
                 when v_game.phase = 'FINALE_REVEAL' or v_game.status = 'finished'
                      then q.prompt
                 when v_game.phase in ('FINALE_PLAYER_ONE', 'FINALE_PLAYER_TWO')
                      and i - 1 <= v_game.finale_q_index
                      then q.prompt
                 else null end
           ) as x
      from generate_series(1, array_length(v_game.finale_question_ids, 1)) i
      join public.tf_questions q on q.id = v_game.finale_question_ids[i]
  ) s;

  select json_agg(y order by slot, q_index) into v_items from (
    select fa.slot, fa.q_index,
           json_build_object(
             'slot', fa.slot,
             'index', fa.q_index,
             'playerId', fa.player_id,
             -- Visible si : on est dans la revelation et l'etape est passee,
             -- ou c'est ma propre reponse, ou la partie est finie.
             'visible', (
               v_game.status = 'finished'
               or fa.player_id = p_uid
               or (v_game.phase = 'FINALE_REVEAL'
                   and (fa.q_index * 2 + (fa.slot - 1)) < v_game.finale_reveal_step)
             ),
             'raw', case when (
                 v_game.status = 'finished'
                 or fa.player_id = p_uid
                 or (v_game.phase = 'FINALE_REVEAL'
                     and (fa.q_index * 2 + (fa.slot - 1)) < v_game.finale_reveal_step)
               ) then fa.raw else null end,
             'label', case when (
                 v_game.status = 'finished'
                 or (v_game.phase = 'FINALE_REVEAL'
                     and (fa.q_index * 2 + (fa.slot - 1)) < v_game.finale_reveal_step)
               ) then fa.label else null end,
             'points', case when (
                 v_game.status = 'finished'
                 or (v_game.phase = 'FINALE_REVEAL'
                     and (fa.q_index * 2 + (fa.slot - 1)) < v_game.finale_reveal_step)
               ) then fa.points else null end,
             'duplicate', fa.duplicate
           ) as y
      from public.tf_finale_answers fa
     where fa.game_id = p_game_id
  ) t;

  return json_build_object(
    'team',        v_game.finale_team,
    'p1',          v_game.finale_p1,
    'p2',          v_game.finale_p2,
    'slot',        v_game.finale_slot,
    'qIndex',      v_game.finale_q_index,
    'revealStep',  v_game.finale_reveal_step,
    'total',       case when v_game.phase = 'FINALE_REVEAL'
                             or v_game.status = 'finished'
                        then v_game.finale_total else null end,
    'target',      public.tf_finale_target(),
    'questions',   coalesce(v_qs, '[]'::json),
    'answers',     coalesce(v_items, '[]'::json)
  );
end;
$$;

-- La charge utile complete renvoyee par toutes les RPC.
create or replace function public._tf_state(p_game_id uuid, p_uid uuid)
returns json
language plpgsql
security definer
set search_path = public
as $$
declare v_game public.tf_games;
begin
  select * into v_game from public.tf_games where id = p_game_id;

  return json_build_object(
    'game',    (select row_to_json(g) from public.tf_games g where g.id = p_game_id),
    'players', coalesce((select json_agg(
                           to_jsonb(p) || jsonb_build_object(
                             'live', p.connected
                                     and p.last_seen > now() - public._tf_live_window())
                           order by p.joined_at, p.id)
                           from public.tf_players p where p.game_id = p_game_id),
                        '[]'::json),
    'board',   public._tf_board(p_game_id),
    'finale',  public._tf_finale(p_game_id, p_uid),
    'hiddenLeft', public._tf_hidden_left(p_game_id),
    'me',      p_uid,
    'serverNow', to_char(now() at time zone 'utc', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
  );
end;
$$;

-- ---------------------------------------------------------------------
-- 7. LE TICK : la seule facon d'avancer quand un chrono expire
--
--   N'importe quel client peut l'appeler. C'est idempotent : le "and
--   phase_seq = ..." et le test sur phase_ends_at font qu'un seul appel
--   passe, meme si six telephones tapent en meme temps.
-- ---------------------------------------------------------------------

create or replace function public._tf_tick(p_game_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_game   public.tf_games;
  v_seq    integer;
  v_rows   integer;
  v_other  uuid;
  v_left   integer;
  v_step   integer;
begin
  select * into v_game from public.tf_games where id = p_game_id;
  if v_game.status = 'finished' then return; end if;
  if v_game.phase_ends_at is null then return; end if;
  if now() < v_game.phase_ends_at then return; end if;

  v_seq := v_game.phase_seq;

  -- Verrou d'avancement : on "consomme" le chrono. Le premier appel gagne,
  -- les autres voient row_count = 0 et ne font rien.
  update public.tf_games
     set phase_ends_at = null
   where id = p_game_id
     and phase_seq = v_seq
     and phase_ends_at is not null;                      -- WHERE obligatoire
  get diagnostics v_rows = row_count;
  if v_rows = 0 then return; end if;

  if v_game.phase = 'INTRO' then
    perform public._tf_begin_round(p_game_id, 1);

  elsif v_game.phase = 'FACE_OFF' then
    perform public._tf_phase(p_game_id, 'BUZZING', 'buzz_open',
      jsonb_build_object('playerR', v_game.faceoff_r, 'playerB', v_game.faceoff_b));

  elsif v_game.phase = 'BUZZING' then
    -- Personne n'a buzze : aucune equipe ne prend la manche. On ne donne
    -- jamais une manche gratuitement.
    perform public._tf_end_round(p_game_id, null, false);

  elsif v_game.phase = 'ANSWERING' then
    -- Temps ecoule sur le face-a-face : compte comme une mauvaise reponse.
    update public.tf_games
       set faceoff_tried = array_append(faceoff_tried, v_game.buzz_winner)
     where id = p_game_id;                               -- WHERE obligatoire
    perform public._tf_phase(p_game_id, 'WRONG_ANSWER', 'wrong_answer',
      jsonb_build_object('scope', 'faceoff', 'player', v_game.buzz_winner,
                         'raw', null, 'timeout', true));

  elsif v_game.phase = 'CORRECT_ANSWER' then
    if v_game.control_team is null then
      -- Bonne reponse du face-a-face : son EQUIPE prend le controle.
      update public.tf_games
         set control_team = (case when v_game.buzz_winner = v_game.faceoff_r
                                  then 'R' else 'B' end)
       where id = p_game_id;                             -- WHERE obligatoire
      perform public._tf_phase(p_game_id, 'CONTROL_GRANTED', 'control_granted',
        jsonb_build_object('team', (select control_team from public.tf_games
                                     where id = p_game_id),
                           'player', v_game.buzz_winner));
    elsif public._tf_hidden_left(p_game_id) = 0 then
      -- Tableau vide : l'equipe encaisse, pas de vol possible.
      perform public._tf_end_round(p_game_id, v_game.control_team, false);
    else
      perform public._tf_next_turn(p_game_id);
    end if;

  elsif v_game.phase = 'WRONG_ANSWER' then
    if v_game.control_team is null then
      -- Face-a-face : la main passe a l'autre, sauf s'il a deja tente.
      v_other := case when v_game.buzz_winner = v_game.faceoff_r
                      then v_game.faceoff_b else v_game.faceoff_r end;
      if v_other is null or v_other = any (v_game.faceoff_tried) then
        perform public._tf_end_round(p_game_id, null, false);
      else
        update public.tf_games
           set buzz_winner = v_other, buzz_at = now()
         where id = p_game_id;                           -- WHERE obligatoire
        perform public._tf_phase(p_game_id, 'ANSWERING', 'hand_over',
          jsonb_build_object('player', v_other));
      end if;
    elsif v_game.strikes >= 3 then
      perform public._tf_phase(p_game_id, 'THREE_STRIKES', 'three_strikes',
        jsonb_build_object('team', v_game.control_team, 'reason', 'strikes',
                           'points', v_game.round_points));
    else
      perform public._tf_next_turn(p_game_id);
    end if;

  elsif v_game.phase = 'CONTROL_GRANTED' then
    perform public._tf_begin_team_turn(p_game_id);

  elsif v_game.phase = 'TEAM_TURN' then
    -- Chrono d'equipe epuise : l'adversaire recoit sa chance unique.
    update public.tf_games set team_ms_left = 0
     where id = p_game_id;                               -- WHERE obligatoire
    perform public._tf_phase(p_game_id, 'THREE_STRIKES', 'three_strikes',
      jsonb_build_object('team', v_game.control_team, 'reason', 'time',
                         'points', v_game.round_points));

  elsif v_game.phase = 'THREE_STRIKES' then
    perform public._tf_begin_steal(p_game_id,
      coalesce(v_game.last_event ->> 'reason', 'strikes'));

  elsif v_game.phase = 'STEAL' then
    -- Personne n'a valide : vol rate, l'equipe en place garde ses points.
    update public.tf_games set steal_success = false
     where id = p_game_id;                               -- WHERE obligatoire
    perform public._tf_phase(p_game_id, 'STEAL_RESULT', 'steal_result',
      jsonb_build_object('success', false, 'team', v_game.steal_team,
                         'raw', null, 'timeout', true,
                         'points', v_game.round_points));

  elsif v_game.phase = 'STEAL_RESULT' then
    if v_game.steal_success then
      perform public._tf_end_round(p_game_id, v_game.steal_team, true);
    else
      perform public._tf_end_round(p_game_id, v_game.control_team, false);
    end if;

  elsif v_game.phase = 'ROUND_RESULT' then
    /*
     * Le client affiche le MEME encart de resultat pendant ROUND_RESULT et
     * ROUND_TRANSITION (TvStage.tsx : RoundResult sur les deux phases), en
     * lisant `winner`/`points`/`stolen` dans last_event. Sans les reprendre
     * ici, le passage a ROUND_TRANSITION ecrasait last_event par un evenement
     * qui n'a que `round`/`next`/`last` : le bon resultat ("+27 pour
     * l'equipe rouge") s'affichait une poignee de secondes puis se faisait
     * remplacer, a l'ecran, par « Personne n'a trouve — aucun point »,
     * meme quand une equipe venait de marquer.
     */
    perform public._tf_phase(p_game_id, 'ROUND_TRANSITION', 'round_transition',
      coalesce(v_game.last_event, '{}'::jsonb) || jsonb_build_object(
                         'round', v_game.round_number,
                         'next', v_game.round_number + 1,
                         'last', v_game.round_number >= public.tf_rounds()));

  elsif v_game.phase = 'ROUND_TRANSITION' then
    if v_game.round_number >= public.tf_rounds() then
      perform public._tf_begin_finale(p_game_id);
    else
      perform public._tf_begin_round(p_game_id, v_game.round_number + 1);
    end if;

  elsif v_game.phase = 'FINALE_INTRO' then
    update public.tf_games set finale_slot = 1, finale_q_index = 0
     where id = p_game_id;                               -- WHERE obligatoire
    perform public._tf_phase(p_game_id, 'FINALE_PLAYER_ONE', 'finale_question',
      jsonb_build_object('slot', 1, 'index', 0, 'player', v_game.finale_p1));

  elsif v_game.phase in ('FINALE_PLAYER_ONE', 'FINALE_PLAYER_TWO') then
    -- Temps ecoule : reponse vide enregistree, on enchaine.
    perform public._tf_finale_record(p_game_id, v_game.finale_slot,
                                     v_game.finale_q_index, '', true);

  elsif v_game.phase = 'FINALE_REVEAL' then
    v_step := v_game.finale_reveal_step + 1;
    if v_step > 10 then
      perform public._tf_finish(p_game_id);
    else
      update public.tf_games set finale_reveal_step = v_step
       where id = p_game_id;                             -- WHERE obligatoire
      perform public._tf_phase(p_game_id, 'FINALE_REVEAL', 'finale_reveal',
        jsonb_build_object('step', v_step));
    end if;
  end if;
end;
$$;

-- Enregistre une reponse de finale et enchaine sur la suite.
create or replace function public._tf_finale_record(
  p_game_id uuid,
  p_slot    integer,
  p_index   integer,
  p_raw     text,
  p_timeout boolean
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_game   public.tf_games;
  v_qid    integer;
  v_aid    bigint;
  v_label  text;
  v_points integer := 0;
  v_dup    boolean := false;
  v_player uuid;
  v_rows   integer;
begin
  select * into v_game from public.tf_games where id = p_game_id;
  v_qid := v_game.finale_question_ids[p_index + 1];
  if v_qid is null then return; end if;

  v_player := case when p_slot = 1 then v_game.finale_p1 else v_game.finale_p2 end;
  v_aid := public._tf_match(v_qid, p_raw);

  if v_aid is not null then
    select label, points into v_label, v_points
      from public.tf_answers where id = v_aid;

    -- Regle classique : le second ne peut pas redonner la reponse du premier.
    if p_slot = 2 and exists (
      select 1 from public.tf_finale_answers
       where game_id = p_game_id and slot = 1 and q_index = p_index
         and answer_id = v_aid
    ) then
      v_dup := true;
      v_points := 0;
    end if;
  else
    v_label := null;
    v_points := 0;
  end if;

  insert into public.tf_finale_answers
        (game_id, slot, q_index, question_id, player_id, raw, answer_id, label,
         points, duplicate)
       values (p_game_id, p_slot, p_index, v_qid, v_player,
               left(btrim(coalesce(p_raw, '')), 60), v_aid, v_label, v_points, v_dup)
  on conflict (game_id, slot, q_index) do nothing;

  get diagnostics v_rows = row_count;
  if v_rows = 0 then return; end if;          -- deja enregistre : idempotent

  update public.tf_games
     set finale_total = finale_total + v_points
   where id = p_game_id;                                 -- WHERE obligatoire

  -- Suite : question suivante, puis joueur suivant, puis revelation.
  if p_index + 1 < coalesce(array_length(v_game.finale_question_ids, 1), 5) then
    update public.tf_games set finale_q_index = p_index + 1
     where id = p_game_id;                               -- WHERE obligatoire
    perform public._tf_phase(p_game_id,
      case when p_slot = 1 then 'FINALE_PLAYER_ONE' else 'FINALE_PLAYER_TWO' end,
      'finale_question',
      jsonb_build_object('slot', p_slot, 'index', p_index + 1,
                         'player', v_player, 'timeout', p_timeout));
  elsif p_slot = 1 then
    update public.tf_games set finale_slot = 2, finale_q_index = 0
     where id = p_game_id;                               -- WHERE obligatoire
    perform public._tf_phase(p_game_id, 'FINALE_PLAYER_TWO', 'finale_switch',
      jsonb_build_object('slot', 2, 'index', 0, 'player', v_game.finale_p2));
  else
    update public.tf_games set finale_reveal_step = 0
     where id = p_game_id;                               -- WHERE obligatoire
    perform public._tf_phase(p_game_id, 'FINALE_REVEAL', 'finale_reveal',
      jsonb_build_object('step', 0));
  end if;
end;
$$;

