create or replace function public.tf_create(p_code text, p_name text, p_team text)
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid  uuid;
  v_code text;
  v_name text;
  v_team text;
  v_id   uuid;
begin
  v_uid  := public._tf_uid();
  v_code := upper(btrim(coalesce(p_code, '')));
  v_name := left(btrim(coalesce(p_name, '')), 18);
  v_team := upper(btrim(coalesce(p_team, 'R')));

  if v_name = '' then
    raise exception 'Choisis un pseudo.' using errcode = 'P0001';
  end if;
  if v_team not in ('R', 'B') then v_team := 'R'; end if;
  if v_code !~ '^[A-Z0-9]{4,6}$' then
    raise exception 'Code de partie invalide.' using errcode = 'P0001';
  end if;
  if exists (select 1 from public.tf_games where code = v_code) then
    raise exception 'Ce code de partie est deja utilise.' using errcode = 'P0001';
  end if;

  insert into public.tf_games (code) values (v_code) returning id into v_id;

  insert into public.tf_players (id, game_id, name, team, connected, faceoff_count, joined_at)
       values (v_uid, v_id, v_name, v_team, true, 0, now())
  on conflict (id) do update
     set game_id = excluded.game_id,
         name = excluded.name,
         team = excluded.team,
         connected = true,
         faceoff_count = 0,
         joined_at = now();

  update public.tf_games set host_player_id = v_uid
   where id = v_id;                                      -- WHERE obligatoire

  return public._tf_state(v_id, v_uid);
end;
$$;

create or replace function public.tf_join(p_code text, p_name text, p_team text)
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid  uuid;
  v_name text;
  v_team text;
  v_game public.tf_games;
  v_n    integer;
begin
  v_uid  := public._tf_uid();
  v_name := left(btrim(coalesce(p_name, '')), 18);
  v_team := upper(btrim(coalesce(p_team, '')));
  v_game := public._tf_game(p_code);

  if v_name = '' then
    raise exception 'Choisis un pseudo.' using errcode = 'P0001';
  end if;
  if v_team not in ('R', 'B') then
    raise exception 'Equipe invalide.' using errcode = 'P0001';
  end if;

  -- Partie deja lancee : seul un joueur deja inscrit peut revenir
  -- (rechargement de page, changement de reseau, telephone verrouille).
  if v_game.status <> 'lobby' then
    if not exists (select 1 from public.tf_players
                    where id = v_uid and game_id = v_game.id) then
      raise exception 'Le show a deja commence' using errcode = 'P0001';
    end if;
    update public.tf_players set connected = true
     where id = v_uid and game_id = v_game.id;           -- WHERE obligatoire
    return public._tf_state(v_game.id, v_uid);
  end if;

  select count(*) into v_n from public.tf_players
   where game_id = v_game.id and team = v_team and id <> v_uid;
  if v_n >= public.tf_max_per_team() then
    raise exception 'Cette equipe est complete' using errcode = 'P0001';
  end if;

  insert into public.tf_players (id, game_id, name, team, connected, faceoff_count, joined_at)
       values (v_uid, v_game.id, v_name, v_team, true, 0, now())
  on conflict (id) do update
     set game_id = excluded.game_id,
         name = excluded.name,
         team = excluded.team,
         connected = true,
         faceoff_count = case when tf_players.game_id is distinct from excluded.game_id
                              then 0 else tf_players.faceoff_count end,
         joined_at = case when tf_players.game_id is distinct from excluded.game_id
                          then now() else tf_players.joined_at end;

  perform public._tf_event(v_game.id, 'player_joined',
    jsonb_build_object('player', v_uid, 'name', v_name, 'team', v_team));

  return public._tf_state(v_game.id, v_uid);
end;
$$;

